#!/usr/bin/env bash
# Regenerates docs/development/measurements/coverage.txt (docs/development/specs/00-infrastructure.md, 3.4): builds
# tools/cpg/enumerate.c against src/theory.c, lists Cadenza's chord space, and classifies the CPG's catalogue against it with
# tools/cpg/coverage.mjs. With --check, compares instead of writing, and fails on any difference (CI).
# Needs gcc, Node 20 or later and the submodule (git submodule update --init third_party/AkaiMPC).
set -euo pipefail
cd "$(dirname "$0")/../.."
CPG=third_party/AkaiMPC/AkaiMPCChordProgressionGenerator
OUT=docs/development/measurements/coverage.txt
[ -f "$CPG/modules/musicTheory.js" ] || { echo "coverage: no CPG in $CPG (git submodule update --init third_party/AkaiMPC)"; exit 1; }
W="$(mktemp -d)"
trap 'rm -rf "$W"' EXIT
"${CC:-gcc}" -std=gnu11 -Wall -Wextra -Werror -Isrc -o "$W/enumerate" tools/cpg/enumerate.c src/theory.c
"$W/enumerate" > "$W/chords.txt"
{
  echo "# Generated by tools/cpg/coverage.sh: do not edit. CI regenerates it and fails on any difference."
  echo "# CPG: liotier/AkaiMPC at $(git -C third_party/AkaiMPC rev-parse --short=7 HEAD), $CPG"
  echo
  node tools/cpg/coverage.mjs "$CPG" "$W/chords.txt"
} > "$W/coverage.txt"
if [ "${1:-}" = --check ]; then
  diff -u "$OUT" "$W/coverage.txt" || { echo "coverage: FAIL: $OUT is out of date (tools/cpg/coverage.sh rewrites it)"; exit 1; }
  echo "coverage: $OUT as committed"
else
  cp "$W/coverage.txt" "$OUT"
  echo "coverage: wrote $OUT"
fi
